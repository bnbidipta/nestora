"""
Eval harness: python -m backend.eval.run [--limit N]
Runs the real pipeline on the synthetic briefs (backend/eval/briefs.json) without touching any house storage,
and writes backend/eval/out/report.md. This replaces the old fault-injection "scorecard".
"""
import argparse
import json
import os
import statistics
import time

from backend.app.models.brief import brief_from_dict
from backend.app.services import orchestrator

HERE = os.path.dirname(__file__)


def _geom(ev):
    return {(r["f"], r["id"]): (r["x"], r["y"], r["w"], r["d"]) for r in ev["preview"]}


def diversity(evs):
    """Mean share of rooms whose rectangle differs between pairs of the top 4."""
    top = evs[:4]
    if len(top) < 2:
        return 0.0
    vals = []
    for i in range(len(top)):
        for j in range(i + 1, len(top)):
            a, b = _geom(top[i]), _geom(top[j])
            keys = set(a) | set(b)
            vals.append(sum(1 for k in keys if a.get(k) != b.get(k)) / len(keys))
    return statistics.mean(vals)


def main():
    import sys
    sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=None)
    args = ap.parse_args()
    rows = json.load(open(os.path.join(HERE, "briefs.json"), encoding="utf-8"))[: args.limit]
    m = {k: [] for k in ("feasible", "cand_pass", "floors_ok", "parking_ok", "bedrooms", "elder_ok", "fsi", "in_budget",
                         "budget_expect_ok", "diversity", "sensitive", "secs")}
    for row in rows:
        b = brief_from_dict(row)
        t = time.time()
        from backend.app.services import generator, llm
        cands = generator.candidates(b, n=24, seed=0, extra_arrangements=[p for p in [llm.propose_arrangement(b)] if p])
        evs = [orchestrator.evaluate(b, c, {}) for c in cands]
        m["secs"].append(time.time() - t)
        good = sorted((e for e in evs if e["judge"]["pass"]), key=lambda e: -e["score"]["total"])
        m["feasible"].append(bool(good))
        if evs:
            m["cand_pass"].append(sum(e["judge"]["pass"] for e in evs) / len(evs))
        if not good:
            continue
        best = good[0]
        fit = best["score"]["brief_fit"]
        m["floors_ok"].append(fit["floors"])
        m["parking_ok"].append(fit["parking"])
        m["bedrooms"].append(fit["bedrooms"])
        if b.elders:
            m["elder_ok"].append(fit["elder_ground"])
        m["fsi"].append(best["summary"]["fsi_used"])
        cost = best["summary"]["cost_inr"]["expected"]
        m["in_budget"].append(cost <= b.budget_inr)
        if "over_budget_likely" in row.get("expect", {}):
            m["budget_expect_ok"].append((cost > b.budget_inr) == row["expect"]["over_budget_likely"])
        m["diversity"].append(diversity(good))
        # input sensitivity: one extra adult (or one fewer floor) must change the best design
        alt = b.model_copy(update={"adults": b.adults + 2})
        alt_c = generator.candidates(alt, n=6, seed=0)
        alt_best = max((orchestrator.evaluate(alt, c, {}) for c in alt_c), key=lambda e: e["score"]["total"], default=None)
        m["sensitive"].append(alt_best is None or _geom(alt_best) != _geom(best))

    pct = lambda xs: f"{100 * sum(xs) / len(xs):.1f}%" if xs else "n/a"
    avg = lambda xs: f"{statistics.mean(xs):.2f}" if xs else "n/a"
    lines = [
        "# Nestora eval report", "",
        f"Briefs: {len(rows)} synthetic (backend/eval/briefs.json, generated by agy, unverified). Rule pack and rates are unverified drafts.", "",
        "| Metric | Value | What it means |", "|---|---|---|",
        f"| Feasible | {pct(m['feasible'])} | Briefs with at least one layout that passes every Judge check. The rest get an honest 'doesn't fit' explanation. |",
        f"| Candidates passing Judge first time | {pct(m['cand_pass'])} | Share of generated candidates that pass with no repair. |",
        f"| Floors as requested | {pct(m['floors_ok'])} | Best option uses the floor count asked for. |",
        f"| Parking as requested | {pct(m['parking_ok'])} | Best option keeps the parking asked for (cars often don't fit 30 ft frontages). |",
        f"| Bedrooms met | {pct(m['bedrooms'])} | Average share of needed bedrooms provided. |",
        f"| Elder on ground floor | {pct(m['elder_ok'])} | Of briefs with elders. Hard rule, so this should be 100%. |",
        f"| FSI used (avg) | {avg(m['fsi'])} | Built-up ÷ plot area. |",
        f"| Within budget (expected cost) | {pct(m['in_budget'])} | Expected cost of the chosen tier ≤ budget. |",
        f"| Agrees with brief's over-budget label | {pct(m['budget_expect_ok'])} | agy's label vs our estimate. |",
        f"| Diversity of top 4 | {avg(m['diversity'])} | Share of rooms placed differently between options (0–1). |",
        f"| Input sensitivity | {pct(m['sensitive'])} | Adding 2 adults changes the best design. |",
        f"| Time per brief (s) | {avg(m['secs'])} | Generate + judge + rank the whole pool. |",
        "", "Pilot gate (plan): ≥ 90% first-pass Judge and architect rating ≥ 4/5 on 50 outputs. The architect rating needs humans (Phase F).",
    ]
    os.makedirs(os.path.join(HERE, "out"), exist_ok=True)
    out = os.path.join(HERE, "out", "report.md")
    open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
